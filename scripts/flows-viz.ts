/// <reference types="node" />
import * as fs from 'node:fs';
import * as path from 'node:path';
import Module from 'node:module';
import { exec } from 'node:child_process';

// Alias react-native to react-native-web for headless Node CLI execution
const origResolve = (Module as any)._resolveFilename;
(Module as any)._resolveFilename = function (request: string, ...args: any[]) {
  if (request === 'react-native') {
    return require.resolve('react-native-web');
  }
  return origResolve.call(this, request, ...args);
};

async function main() {
  // Dynamically import registry and journeys after setting up module alias
  const { registry } = await import('../src/flows/core/registry');
  const { journeyToMermaid, resolveStepTransition } = await import(
    '../src/flows/viz/mermaid'
  );
  const { generateHtmlVisualizer } = await import('../src/flows/viz/html-generator');
  const { journeyABRegistry } = await import('../src/flows/ab/registry');

  // Load and register all journeys
  await import('../src/journeys');

  const projectRoot = path.resolve(__dirname, '..');
  const docsDir = path.join(projectRoot, 'docs');
  const vizDir = path.join(projectRoot, 'flows-viz');

  if (!fs.existsSync(docsDir)) {
    fs.mkdirSync(docsDir, { recursive: true });
  }
  if (!fs.existsSync(vizDir)) {
    fs.mkdirSync(vizDir, { recursive: true });
  }

  const journeys = registry.getAllJourneys();

  console.log('\n======================================================');
  console.log('⚡ Flow Orchestration Engine: Visualization Compiler');
  console.log('======================================================\n');
  console.log(`Discovered ${journeys.length} Journeys in src/journeys:\n`);

  // 1. Build Markdown documentation
  const mdLines: string[] = [
    '# Flow Orchestration & State Machine Documentation',
    '',
    'This file is automatically generated by `npm run flows:viz`. It documents all registered journeys, their variants, subflows, and state machine transitions.',
    '',
    '## Table of Contents',
    ...journeys.map((j) => `- [${j.name} (\`${j.id}\`)](#journey-${j.id.toLowerCase()})`),
    '',
    '---',
  ];

  for (const journey of journeys) {
    console.log(`▶ Journey: ${journey.name} (id: "${journey.id}")`);
    mdLines.push(`## Journey: ${journey.name}`);
    mdLines.push(`**ID**: \`${journey.id}\``);
    if (journey.description) {
      mdLines.push(`**Description**: ${journey.description}`);
    }
    mdLines.push('');

    for (const [variantKey, flow] of Object.entries(journey.variants)) {
      const isControl = variantKey === 'control';
      console.log(
        `  └─ Variant: "${variantKey}" ${isControl ? '(Control / Baseline)' : ''} [${Object.keys(flow.steps).length} steps]`
      );
      mdLines.push(
        `### Variant: \`${variantKey}\` ${isControl ? '*(Control / Default)*' : ''}`
      );
      mdLines.push('');
      mdLines.push('```mermaid');
      mdLines.push(journeyToMermaid(journey, variantKey));
      mdLines.push('```');
      mdLines.push('');

      mdLines.push('| Step ID | Title | Type | Next Target |');
      mdLines.push('| :--- | :--- | :--- | :--- |');
      const knownStepIds = Object.keys(flow.steps);
      for (const [stepId, s] of Object.entries(flow.steps)) {
        const type = s.type ?? 'screen';
        const title = s.title ?? stepId;
        const transition = s.type === 'subflow' ? (s as any).onComplete : (s as any).next;
        const res = resolveStepTransition(
          transition,
          knownStepIds,
          s.title,
          (s as any).branches,
          (s as any).decisionLabel
        );

        let next = '*[Terminal]*';
        if (!res || res.branches.length === 0) {
          next = '*[Terminal]*';
        } else if (!res.isConditional && res.branches.length === 1) {
          next = `\`${res.branches[0].target}\``;
        } else {
          next = res.branches
            .map((b) => (b.label ? `**${b.label}** &rarr; \`${b.target}\`` : `\`${b.target}\``))
            .join(' \\| ');
        }
        mdLines.push(`| \`${stepId}\` | ${title} | \`${type}\` | ${next} |`);
      }
      mdLines.push('');
    }
    mdLines.push('---');
  }

  const markdownPath = path.join(docsDir, 'flows.md');
  fs.writeFileSync(markdownPath, mdLines.join('\n'), 'utf-8');

  // 2. Build Interactive HTML Visualizer
  const abMappings = journeyABRegistry.getAll();
  const htmlContent = generateHtmlVisualizer(journeys, abMappings);
  const htmlPath = path.join(vizDir, 'index.html');
  fs.writeFileSync(htmlPath, htmlContent, 'utf-8');

  console.log('\n✅ Visualization artifacts generated successfully:');
  console.log(`   📄 Markdown Documentation: ${markdownPath}`);
  console.log(`   🌐 Interactive Web Visualizer: ${htmlPath}`);

  const rawArgs = process.argv.slice(2);
  const shouldOpen =
    rawArgs.includes('-open') ||
    rawArgs.includes('--open') ||
    rawArgs.includes('open') ||
    rawArgs.some((arg) => arg.toLowerCase().includes('open')) ||
    process.env.OPEN === 'true';

  if (shouldOpen) {
    console.log('\n🚀 Opening visualizer in your default browser...');
    const cmd =
      process.platform === 'darwin'
        ? `open "${htmlPath}"`
        : process.platform === 'win32'
        ? `start "" "${htmlPath}"`
        : `xdg-open "${htmlPath}"`;

    exec(cmd, (err) => {
      if (err) {
        console.warn(`[flows:viz] Could not automatically open browser: ${err.message}`);
      }
    });
  } else {
    console.log('\nTo preview the visualizer in your browser:');
    console.log(`   open "${htmlPath}"`);
    console.log('   (Tip: pass "-open" to open automatically)');
  }
  console.log('======================================================\n');
}

main().catch((err) => {
  console.error('[flows:viz] Error during compilation:', err);
  process.exit(1);
});
